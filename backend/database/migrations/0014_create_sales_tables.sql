-- Ventas: pedidos, items, pago, comentarios, transacciones (Webkul Sales).
-- Estados: pending | pending_payment | processing | completed | canceled | closed | fraud.
CREATE TABLE IF NOT EXISTS `orders` (
    `id` BIGINT PRIMARY KEY AUTOINCREMENT,
    `increment_id` VARCHAR(255) NULL UNIQUE,
    `status` VARCHAR(255) NOT NULL DEFAULT 'pending',
    `channel_name` VARCHAR(255) NULL,
    `is_guest` BOOLEAN NOT NULL DEFAULT 0,
    `customer_email` VARCHAR(255) NULL,
    `customer_first_name` VARCHAR(255) NULL,
    `customer_last_name` VARCHAR(255) NULL,
    `shipping_method` VARCHAR(255) NULL,
    `shipping_title` VARCHAR(255) NULL,
    `shipping_description` VARCHAR(255) NULL,
    `coupon_code` VARCHAR(255) NULL,
    `applied_cart_rule_ids` LONGTEXT NULL,
    `is_gift` BOOLEAN NOT NULL DEFAULT 0,
    `total_item_count` INTEGER NOT NULL DEFAULT 0,
    `total_qty_ordered` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `exchange_rate` DECIMAL(12,4) NOT NULL DEFAULT 1,
    `base_currency_code` VARCHAR(255) NULL,
    `channel_currency_code` VARCHAR(255) NULL,
    `order_currency_code` VARCHAR(255) NULL,
    `grand_total` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `base_grand_total` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `grand_total_invoiced` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `base_grand_total_invoiced` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `grand_total_refunded` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `base_grand_total_refunded` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `sub_total` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `base_sub_total` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `sub_total_incl_tax` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `base_sub_total_incl_tax` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `sub_total_invoiced` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `base_sub_total_invoiced` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `sub_total_refunded` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `base_sub_total_refunded` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `discount_percent` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `discount_amount` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `base_discount_amount` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `discount_invoiced` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `base_discount_invoiced` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `discount_refunded` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `base_discount_refunded` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `tax_amount` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `base_tax_amount` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `tax_amount_invoiced` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `base_tax_amount_invoiced` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `tax_amount_refunded` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `base_tax_amount_refunded` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `shipping_amount` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `base_shipping_amount` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `shipping_amount_incl_tax` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `base_shipping_amount_incl_tax` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `shipping_invoiced` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `base_shipping_invoiced` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `shipping_refunded` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `base_shipping_refunded` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `shipping_discount_amount` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `base_shipping_discount_amount` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `customer_id` BIGINT NULL,
    `customer_type` VARCHAR(255) NULL,
    `channel_id` BIGINT NULL,
    `channel_type` VARCHAR(255) NULL,
    `cart_id` BIGINT NULL,
    `created_at` DATETIME NULL,
    `updated_at` DATETIME NULL,
    FOREIGN KEY (`customer_id`) REFERENCES `customers`(`id`) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS `orders_customer_id_index` ON `orders` (`customer_id`);
CREATE INDEX IF NOT EXISTS `orders_created_at_index` ON `orders` (`created_at`);

CREATE TABLE IF NOT EXISTS `order_items` (
    `id` BIGINT PRIMARY KEY AUTOINCREMENT,
    `sku` VARCHAR(255) NULL,
    `type` VARCHAR(255) NULL,
    `name` VARCHAR(255) NULL,
    `coupon_code` VARCHAR(255) NULL,
    `weight` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `total_weight` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `qty_ordered` INTEGER NOT NULL DEFAULT 0,
    `qty_shipped` INTEGER NOT NULL DEFAULT 0,
    `qty_invoiced` INTEGER NOT NULL DEFAULT 0,
    `qty_canceled` INTEGER NOT NULL DEFAULT 0,
    `qty_refunded` INTEGER NOT NULL DEFAULT 0,
    `price` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `base_price` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `price_incl_tax` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `base_price_incl_tax` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `total` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `base_total` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `total_incl_tax` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `base_total_incl_tax` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `total_invoiced` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `base_total_invoiced` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `amount_refunded` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `base_amount_refunded` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `discount_percent` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `discount_amount` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `base_discount_amount` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `discount_invoiced` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `base_discount_invoiced` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `discount_refunded` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `base_discount_refunded` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `tax_percent` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `tax_amount` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `base_tax_amount` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `tax_amount_invoiced` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `base_tax_amount_invoiced` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `tax_amount_refunded` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `base_tax_amount_refunded` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `product_id` BIGINT NULL,
    `product_type` VARCHAR(255) NULL,
    `order_id` BIGINT NULL,
    `parent_id` BIGINT NULL,
    `tax_category_id` BIGINT NULL,
    `additional` JSON NULL,
    `created_at` DATETIME NULL,
    `updated_at` DATETIME NULL,
    FOREIGN KEY (`order_id`) REFERENCES `orders`(`id`) ON DELETE CASCADE,
    FOREIGN KEY (`parent_id`) REFERENCES `order_items`(`id`) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS `order_items_order_id_index` ON `order_items` (`order_id`);

CREATE TABLE IF NOT EXISTS `order_payment` (
    `id` BIGINT PRIMARY KEY AUTOINCREMENT,
    `method` VARCHAR(255) NULL,
    `method_title` VARCHAR(255) NULL,
    `additional` JSON NULL,
    `order_id` BIGINT NULL,
    `created_at` DATETIME NULL,
    `updated_at` DATETIME NULL,
    FOREIGN KEY (`order_id`) REFERENCES `orders`(`id`) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS `order_comments` (
    `id` BIGINT PRIMARY KEY AUTOINCREMENT,
    `comment` LONGTEXT NULL,
    `customer_notified` BOOLEAN NOT NULL DEFAULT 0,
    `order_id` BIGINT NULL,
    `user_id` BIGINT NULL,
    `created_at` DATETIME NULL,
    `updated_at` DATETIME NULL,
    FOREIGN KEY (`order_id`) REFERENCES `orders`(`id`) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS `order_transactions` (
    `id` BIGINT PRIMARY KEY AUTOINCREMENT,
    `transaction_id` VARCHAR(255) NULL,
    `status` VARCHAR(255) NULL,
    `type` VARCHAR(255) NULL,
    `amount` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `base_amount` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `payment_method` VARCHAR(255) NULL,
    `data` JSON NULL,
    `invoice_id` BIGINT NULL,
    `order_id` BIGINT NULL,
    `created_at` DATETIME NULL,
    `updated_at` DATETIME NULL,
    FOREIGN KEY (`order_id`) REFERENCES `orders`(`id`) ON DELETE CASCADE
);
