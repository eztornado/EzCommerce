-- Facturas, envíos y reembolsos (Webkul Sales).
-- Factura: state pending | pending_payment | paid | overdue | refunded. Reembolso: state='refunded'.
CREATE TABLE IF NOT EXISTS `invoices` (
    `id` BIGINT PRIMARY KEY AUTOINCREMENT,
    `increment_id` VARCHAR(255) NULL,
    `state` VARCHAR(255) NOT NULL DEFAULT 'paid',
    `email_sent` BOOLEAN NOT NULL DEFAULT 0,
    `total_qty` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `base_currency_code` VARCHAR(255) NULL,
    `channel_currency_code` VARCHAR(255) NULL,
    `order_currency_code` VARCHAR(255) NULL,
    `sub_total` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `base_sub_total` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `sub_total_incl_tax` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `base_sub_total_incl_tax` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `grand_total` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `base_grand_total` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `shipping_amount` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `base_shipping_amount` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `shipping_amount_incl_tax` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `base_shipping_amount_incl_tax` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `tax_amount` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `base_tax_amount` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `discount_amount` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `base_discount_amount` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `transaction_id` VARCHAR(255) NULL,
    `order_id` BIGINT NULL,
    `reminders` INTEGER NOT NULL DEFAULT 0,
    `next_reminder_at` DATETIME NULL,
    `created_at` DATETIME NULL,
    `updated_at` DATETIME NULL,
    FOREIGN KEY (`order_id`) REFERENCES `orders`(`id`) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS `invoice_items` (
    `id` BIGINT PRIMARY KEY AUTOINCREMENT,
    `name` VARCHAR(255) NULL,
    `description` LONGTEXT NULL,
    `sku` VARCHAR(255) NULL,
    `qty` INTEGER NOT NULL DEFAULT 0,
    `price` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `base_price` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `price_incl_tax` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `base_price_incl_tax` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `total` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `base_total` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `total_incl_tax` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `base_total_incl_tax` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `tax_amount` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `base_tax_amount` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `discount_percent` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `discount_amount` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `base_discount_amount` DECIMAL(12,4) NOT NULL DEFAULT 0,
    `product_id` BIGINT NULL,
    `product_type` VARCHAR(255) NULL,
    `order_item_id` BIGINT NULL,
    `invoice_id` BIGINT NULL,
    `parent_id` BIGINT NULL,
    `additional` JSON NULL,
    `created_at` DATETIME NULL,
    `updated_at` DATETIME NULL,
    FOREIGN KEY (`invoice_id`) REFERENCES `invoices`(`id`) ON DELETE CASCADE,
    FOREIGN KEY (`parent_id`) REFERENCES `invoice_items`(`id`) ON DELETE CASCADE
);

