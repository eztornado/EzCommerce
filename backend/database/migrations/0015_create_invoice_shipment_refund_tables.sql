-- Direcciones polimórficas (customer_address | cart_shipping | cart_billing |
-- order_shipping | order_billing); viene al final porque referencia cart/orders.
CREATE TABLE IF NOT EXISTS `addresses` (
    `id` BIGINT PRIMARY KEY AUTOINCREMENT,
    `address_type` VARCHAR(255) NULL,
    `parent_address_id` BIGINT NULL,
    `first_name` VARCHAR(255) NULL,
    `last_name` VARCHAR(255) NULL,
    `gender` VARCHAR(255) NULL,
    `company_name` VARCHAR(255) NULL,
    `address1` LONGTEXT NULL,
    `address2` LONGTEXT NULL,
    `city` VARCHAR(255) NULL,
    `state` VARCHAR(255) NULL,
    `country` VARCHAR(255) NULL,
    `postcode` VARCHAR(255) NULL,
    `email` VARCHAR(255) NULL,
    `phone` VARCHAR(255) NULL,
    `vat_id` VARCHAR(255) NULL,
    `default_address` BOOLEAN NOT NULL DEFAULT 0,
    `use_for_shipping` BOOLEAN NOT NULL DEFAULT 0,
    `additional` JSON NULL,
    `customer_id` BIGINT NULL,
    `cart_id` BIGINT NULL,
    `order_id` BIGINT NULL,
    `created_at` DATETIME NULL,
    `updated_at` DATETIME NULL,
    FOREIGN KEY (`parent_address_id`) REFERENCES `addresses`(`id`) ON DELETE SET NULL,
    FOREIGN KEY (`customer_id`) REFERENCES `customers`(`id`) ON DELETE CASCADE,
    FOREIGN KEY (`cart_id`) REFERENCES `cart`(`id`) ON DELETE CASCADE,
    FOREIGN KEY (`order_id`) REFERENCES `orders`(`id`) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS `addresses_customer_id_index` ON `addresses` (`customer_id`);
CREATE INDEX IF NOT EXISTS `addresses_cart_id_index` ON `addresses` (`cart_id`);
CREATE INDEX IF NOT EXISTS `addresses_order_id_index` ON `addresses` (`order_id`);
